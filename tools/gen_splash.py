"""Generate firmware/gen/prysm_splash.h from assets/splash.jpg: the power-on picture, in the panel's format.

  tools/gen_splash.py        (needs Pillow; the header is checked in, rerun after changing the picture)

RGB565, byte-swapped as the canvas keeps its pixels (gfx.c), so the app copies rows straight into the canvas and
blits them. The picture is used at its own size (pixel art: no uneven scaling) and centred by the app.
Also writes build/splash-preview.png: the screen as the FM-1 will show it.
"""
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "assets" / "splash.jpg"
OUT = ROOT / "firmware" / "gen" / "prysm_splash.h"


def rgb565_swapped(r, g, b):
    c = (r >> 3) << 11 | (g >> 2) << 5 | b >> 3
    return (c >> 8) | (c & 0xFF) << 8


def main():
    im = Image.open(SRC).convert("RGB")
    w, h = im.size
    assert w <= 240 and h <= 204, "the picture leaves 36 rows under it for the name"
    px = [rgb565_swapped(*im.getpixel((x, y))) for y in range(h) for x in range(w)]
    rows = [", ".join(f"0x{v:04X}" for v in px[i:i + 16]) for i in range(0, len(px), 16)]
    OUT.write_text("/* SPDX-License-Identifier: GPL-3.0-only */\n"
                   "/* generated by tools/gen_splash.py from assets/splash.jpg: do not edit */\n"
                   f"#define SPLASH_W {w}u\n#define SPLASH_H {h}u\n"
                   "static const uint16_t SPLASH[SPLASH_W * SPLASH_H] = {\n    " + ",\n    ".join(rows) + "};\n")
    prev = Image.new("RGB", (240, 240))           # the preview: as the panel shows it (RGB565, centred, the name under)
    prev.paste(Image.merge("RGB", [b.point(lambda v, s=s: (v >> s) << s) for b, s in zip(im.split(), (3, 2, 3))]),
               ((240 - w) // 2, 4))
    (ROOT / "build").mkdir(exist_ok=True)
    prev.save(ROOT / "build" / "splash-preview.png")
    print(f"{OUT}: {w} x {h}, {len(px) * 2} bytes; preview build/splash-preview.png")


if __name__ == "__main__":
    main()
