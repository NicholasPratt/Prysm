"""FONT_M (the focus row's values) from a Terminus BDF -> firmware/gen/prysm_font_m.h, in gfx.c's felucca_font_t
layout: ASCII 32..126, each glyph the whole cell (bw = the cell's width, 4 bits a pixel: 0 or 15).

    tools/gen_font_m.py ter-u24b.bdf

Terminus (http://terminus-font.sourceforge.net, SIL Open Font License 1.1) by Dimitar Toshkov Zhekov."""
import sys
from pathlib import Path

FIRST, LAST = 32, 126


def parse(path):
    glyphs, fbb, cur, rows = {}, None, None, None
    for line in Path(path).read_text(encoding="latin-1").splitlines():
        w = line.split()
        if not w:
            continue
        if w[0] == "FONTBOUNDINGBOX":
            fbb = tuple(int(v) for v in w[1:5])
        elif w[0] == "ENCODING":
            cur = {"enc": int(w[1])}
        elif w[0] == "BBX" and cur is not None:
            cur["bbx"] = tuple(int(v) for v in w[1:5])
        elif w[0] == "BITMAP" and cur is not None:
            rows = []
        elif w[0] == "ENDCHAR" and cur is not None:
            cur["rows"] = rows
            glyphs[cur["enc"]] = cur
            cur, rows = None, None
        elif rows is not None:
            rows.append(int(w[0], 16))
    return fbb, glyphs


def main():
    fbb, glyphs = parse(sys.argv[1])
    cw, ch, fx, fy = fbb                        # the cell; its origin below the baseline
    bpr = (cw + 1) // 2
    data, off = [], []
    for c in range(FIRST, LAST + 1):
        g = glyphs.get(c, glyphs[ord("?")])
        gw, gh, gx, gy = g["bbx"]
        nbits = ((gw + 7) // 8) * 8
        cell = [[0] * cw for _ in range(ch)]
        top = ch - (gy - fy) - gh               # the glyph's first row in the cell
        for r, bits in enumerate(g["rows"]):
            for x in range(gw):
                if bits >> (nbits - 1 - x) & 1:
                    yy, xx = top + r, x + gx - fx
                    if 0 <= yy < ch and 0 <= xx < cw:
                        cell[yy][xx] = 15
        off.append(len(data))
        for y in range(ch):
            for x in range(0, cw, 2):
                a = cell[y][x]
                b = cell[y][x + 1] if x + 1 < cw else 0
                data.append(a << 4 | b)
    n = LAST - FIRST + 1
    out = [f"/* generated by tools/gen_font_m.py from {Path(sys.argv[1]).name} (Terminus, SIL OFL 1.1): FONT_M, "
           f"{cw} x {ch}, ASCII {FIRST}..{LAST} */",
           f"static const uint8_t FONT_M_DATA[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        out.append("    " + ", ".join(f"0x{v:02X}" for v in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const uint16_t FONT_M_OFF[{n}] = {{{', '.join(map(str, off))}}};")
    out.append(f"static const uint8_t FONT_M_ADV[{n}] = {{{', '.join([str(cw)] * n)}}};")
    out.append(f"static const uint8_t FONT_M_BW[{n}] = {{{', '.join([str(cw)] * n)}}};")
    out.append(f"static const felucca_font_t FONT_M = {{ {ch}, 0, {FIRST}, {LAST}, FONT_M_ADV, FONT_M_BW, FONT_M_OFF, "
               "FONT_M_DATA };")
    dest = Path(__file__).resolve().parent.parent / "firmware" / "gen" / "prysm_font_m.h"
    dest.write_text("\n".join(out) + "\n")
    print(f"{dest}: {n} glyphs, {len(data)} bytes")


if __name__ == "__main__":
    main()
